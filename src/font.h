/* ---- drawing primitives ---- */

static void ps_draw_char(u32 *fb, int x, int y, char ch, u32 color, int scale) {
    if (ch < 0x20 || ch > 0x7F) ch = '?';
    const u8 *g = ps_font8x8[(u8)ch - 0x20];
    for (int row = 0; row < 8; row++) {
        u8 bits = g[row];
        for (int col = 0; col < 8; col++) {
            if (!(bits & (0x80 >> col))) continue;
            int bx = x + col * scale;
            int by = y + row * scale;
            for (int dy = 0; dy < scale; dy++) {
                int py = by + dy;
                if (py < 0 || py >= SCR_H) continue;
                u32 *rp = fb + py * SCR_W;
                for (int dx = 0; dx < scale; dx++) {
                    int px = bx + dx;
                    if (px < 0 || px >= SCR_W) continue;
                    rp[px] = color;
                }
            }
        }
    }
}

static void ps_draw_str(u32 *fb, int x, int y, const char *s, u32 color, int scale) {
    while (*s) {
        ps_draw_char(fb, x, y, *s, color, scale);
        x += 8 * scale;
        s++;
    }
}

static void ps_draw_str_center(u32 *fb, int y, const char *s, u32 color, int scale) {
    int n = 0;
    while (s[n]) n++;
    ps_draw_str(fb, (SCR_W - n * 8 * scale) / 2, y, s, color, scale);
}

static void ps_fill_rect(u32 *fb, int x, int y, int w, int h, u32 color) {
    for (int j = 0; j < h; j++) {
        int py = y + j;
        if (py < 0 || py >= SCR_H) continue;
        u32 *row = fb + py * SCR_W;
        for (int i = 0; i < w; i++) {
            int px = x + i;
            if (px < 0 || px >= SCR_W) continue;
            row[px] = color;
        }
    }
}

